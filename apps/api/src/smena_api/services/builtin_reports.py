def seed_builtin(conn: Connection) -> None:
    """Insert the system rows idempotently (ON CONFLICT DO NOTHING).

    Used by the seed migration and the test fixtures; keeps production and
    test data byte-identical. ``conn`` is the caller's (sync) connection —
    the caller owns the transaction.
    """
    for row in BUILTIN_REPORT_TEMPLATES:
        conn.execute(
            pg_insert(templates_table)
            .values(
                id=uuid.UUID(row["id"]),
                owner_id=None,
                name=row["name"],
                entity_type="report",
                payload=row["payload"],
            )
            .on_conflict_do_nothing()
        )
